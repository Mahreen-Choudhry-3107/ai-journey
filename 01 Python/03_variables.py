# Python Variables

#  A variable is a name that stores a value in memory. Think of it as a labeled box: the label is the name, and the box holds the data. You can use variables to store different types of data, such as numbers, text, or more complex data structures.


# Creating variables
x = 5 # Integer
y = "Hello, World!" # String
z = 3.14 # Float

# Printing variables
print(x)  # Output: 5
print(y)  # Output: Hello, World!
print(z)  # Output: 3.14

# Naming conventions
# Naming rules (must follow)
# Must start with a letter or underscore (_), never a number
# Can contain letters, numbers, and underscores only
# No spaces or special characters (-, @, $)
# Case-sensitive: age, Age, and AGE are three different variables
# Cannot be a Python keyword (if, for, class, etc.)

my_name = "Ali"     # valid
_score = 90         # valid
name2 = "Sara"      # valid

