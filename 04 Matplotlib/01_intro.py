# Introduction to Matplotlib
# Key Term you must know


# Data Point: A data point is a single unit of data that represents a specific value or measurement in a dataset. In the context of Matplotlib, data points are often represented as coordinates on a graph, where each point corresponds to a specific value on the x-axis and y-axis.

# Axis: An axis is a line that represents a dimension in a plot. In Matplotlib, there are typically two axes: the x-axis (horizontal) and the y-axis (vertical).

# Figure: A figure is the entire window or page that contains one or more plots. In Matplotlib, a figure can contain multiple subplots, each with its own axes.

# Plot: A plot is a graphical representation of data points on a coordinate system. In Matplotlib, plots can take various forms, such as line plots, scatter plots, bar plots, etc.

# Marker: A marker is a symbol used to represent individual data points on a plot. In Matplotlib, markers can take various shapes, such as circles, squares, triangles, etc., and can be customized in terms of size and color.

# Line Style: Line style refers to the appearance of lines in a plot. In Matplotlib, line styles can be solid, dashed, dotted, or dash-dot, and they can be customized using different parameters.

# Colors: Colors are used to differentiate between different data series or elements in a plot. In Matplotlib, colors can be specified using names, hexadecimal codes, or RGB values.

# Legend: A legend is a key that explains the meaning of different elements in a plot, such as lines, markers, or colors. In Matplotlib, legends can be added to plots to provide context and improve readability.

# Labels: Labels are text annotations that provide information about the axes, data points, or other elements in a plot. In Matplotlib, labels can be added to the x-axis, y-axis, and individual data points to enhance understanding.

# Title: A title is a descriptive heading that provides context for a plot. In Matplotlib, titles can be added to figures or individual subplots to summarize the content of the visualization.